/**
 * Typed bridge between the MAIN-world WebAuthn shim and the extension.
 *
 * `navigator.credentials` can only be intercepted from the page's own world,
 * which has no access to the extension API. The shim therefore posts a message
 * tagged with a per-page nonce, the ISOLATED content script relays it to the
 * service worker (and from there to the daemon), and the answer comes back the
 * same way. The nonce stops the page itself from injecting a fake answer.
 *
 * When the daemon cannot serve the ceremony — no passkey stored, vault locked,
 * user refusal — the shim calls the original browser function, so enabling
 * Akooti never breaks a site.
 */

/** Channel name shared by both worlds. */
export const WEBAUTHN_CHANNEL = "akooti-webauthn";

/** Ceremony requested by the page. */
export type CeremonyKind = "create" | "get";

/** Message posted by the shim. */
export interface WebauthnRequest {
  channel: typeof WEBAUTHN_CHANNEL;
  /** Per-page random tag, generated by the ISOLATED world. */
  nonce: string;
  /** Correlates the reply with the waiting ceremony. */
  id: string;
  kind: CeremonyKind;
  /** Relying party id read from the options, when the shape allows it. */
  rpId: string | null;
  /** Whether a user gesture was already consumed by the page. */
  userVerification: string | null;
}

/** Message posted back by the ISOLATED world. */
export interface WebauthnReply {
  channel: typeof WEBAUTHN_CHANNEL;
  nonce: string;
  id: string;
  /** `true` when the daemon produced a credential; `false` means "fall back". */
  handled: boolean;
  /** Non-revealing reason, for the console and the popup diagnostics. */
  reason: string | null;
  /** Serialised `PublicKeyCredential` fields, when handled. */
  credential: Record<string, unknown> | null;
}

/** Whether a page message is a well-formed request. */
export function isWebauthnRequest(value: unknown): value is WebauthnRequest {
  if (typeof value !== "object" || value === null) {
    return false;
  }
  const candidate = value as Partial<WebauthnRequest>;
  return (
    candidate.channel === WEBAUTHN_CHANNEL &&
    typeof candidate.nonce === "string" &&
    candidate.nonce.length > 0 &&
    typeof candidate.id === "string" &&
    (candidate.kind === "create" || candidate.kind === "get") &&
    (candidate.rpId === null || typeof candidate.rpId === "string") &&
    (candidate.userVerification === null || typeof candidate.userVerification === "string")
  );
}

/** Whether a page message is a well-formed reply. */
export function isWebauthnReply(value: unknown): value is WebauthnReply {
  if (typeof value !== "object" || value === null) {
    return false;
  }
  const candidate = value as Partial<WebauthnReply>;
  return (
    candidate.channel === WEBAUTHN_CHANNEL &&
    typeof candidate.nonce === "string" &&
    typeof candidate.id === "string" &&
    typeof candidate.handled === "boolean" &&
    (candidate.reason === null || typeof candidate.reason === "string") &&
    (candidate.credential === null || typeof candidate.credential === "object")
  );
}

/** Whether a reply answers this request and comes from the extension. */
export function isReplyTo(request: WebauthnRequest, value: unknown): value is WebauthnReply {
  return isWebauthnReply(value) && value.id === request.id && value.nonce === request.nonce;
}

/**
 * Whether a page of that host may ask for credentials of that relying party.
 *
 * The WebAuthn rule is "equal to, or a registrable suffix of, the origin host":
 * `example.com` may ask for `example.com` and `com` would be a public suffix,
 * which the browser itself rejects. The check happens in the extension because
 * a page controls the `rpId` it puts in the options: without it, any site could
 * ask for another site's credential. `null` means "the browser derives it".
 */
export function isRelyingPartyAllowed(rpId: string | null, hostname: string): boolean {
  if (rpId === null || rpId.length === 0) {
    return true;
  }
  const rp = rpId.toLowerCase();
  const host = hostname.toLowerCase();
  if (rp === host) {
    return true;
  }
  // A single label (`com`, `local`) is never a registrable suffix.
  return rp.includes(".") && host.endsWith(`.${rp}`);
}

/** Timer pair, injected so timeouts are testable and never leak. */
export interface CeremonyClock {
  schedule(handler: () => void, milliseconds: number): unknown;
  cancel(handle: unknown): void;
}

const defaultClock: CeremonyClock = {
  schedule: (handler, milliseconds) => setTimeout(handler, milliseconds),
  cancel: (handle) => clearTimeout(handle as number),
};

/**
 * Target origin for `window.postMessage` inside one page.
 *
 * A sandboxed frame reports `"null"` as its origin, and `postMessage` refuses
 * that string; `"*"` is then used. It only ever targets the posting window
 * itself, and the nonce still authenticates the message.
 */
export function pageMessageTarget(origin: string): string {
  return origin === "null" || origin.length === 0 ? "*" : origin;
}

interface Waiting {
  request: WebauthnRequest;
  resolve(reply: WebauthnReply): void;
  reject(error: Error): void;
  timer: unknown;
}

/**
 * Waits for one ceremony reply at a time, with an explicit timeout.
 *
 * A timeout is not an error for the user: the shim falls back to the browser
 * authenticator, so the site keeps working even when the desktop app is closed.
 */
export class WebauthnRelay {
  private readonly waiting = new Map<string, Waiting>();
  private counter = 0;

  constructor(
    private readonly post: (message: unknown) => void,
    private readonly nonce: string,
    private readonly clock: CeremonyClock = defaultClock,
    private readonly timeoutMs = 60_000,
  ) {}

  /** Sends a ceremony to the extension and waits for the reply. */
  send(
    kind: CeremonyKind,
    options: { rpId?: string | null; userVerification?: string | null } = {},
  ): Promise<WebauthnReply> {
    this.counter += 1;
    const request: WebauthnRequest = {
      channel: WEBAUTHN_CHANNEL,
      nonce: this.nonce,
      id: `${kind}-${this.counter}`,
      kind,
      rpId: options.rpId ?? null,
      userVerification: options.userVerification ?? null,
    };
    return new Promise<WebauthnReply>((resolve, reject) => {
      const timer = this.clock.schedule(() => {
        if (!this.waiting.delete(request.id)) {
          return;
        }
        reject(new Error("akooti: the daemon did not answer the passkey ceremony"));
      }, this.timeoutMs);
      this.waiting.set(request.id, { request, resolve, reject, timer });
      this.post(request);
    });
  }

  /** Routes one page message; returns `true` when it answered a pending call. */
  receive(value: unknown): boolean {
    if (typeof value !== "object" || value === null) {
      return false;
    }
    const id = (value as Partial<WebauthnReply>).id;
    if (typeof id !== "string") {
      return false;
    }
    const pending = this.waiting.get(id);
    if (!pending || !isReplyTo(pending.request, value)) {
      return false;
    }
    this.settle(pending);
    pending.resolve(value);
    return true;
  }

  /** Rejects every pending ceremony, used when the extension goes away. */
  cancel(reason = "akooti: the passkey bridge stopped"): void {
    for (const pending of [...this.waiting.values()]) {
      this.settle(pending);
      pending.reject(new Error(reason));
    }
  }

  /** Drops one ceremony and its timer, so nothing fires afterwards. */
  private settle(pending: Waiting): void {
    this.waiting.delete(pending.request.id);
    this.clock.cancel(pending.timer);
  }

  /** Number of ceremonies currently waiting; used by tests. */
  get pending(): number {
    return this.waiting.size;
  }
}
